import {DatabaseSync} from 'node:sqlite';
import{mkdirSync,writeFileSync}from'node:fs';
const db=new DatabaseSync(process.env.DB_PATH || 'data/3maine.db',{readOnly:true});
let sql=`BEGIN;
CREATE SCHEMA IF NOT EXISTS lume;
CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA extensions;
SET search_path TO lume,extensions,public;
CREATE OR REPLACE FUNCTION lume.datetime(value text, modifier text DEFAULT NULL) RETURNS text LANGUAGE sql STABLE AS $$
 SELECT to_char((CASE WHEN value='now' THEN now() AT TIME ZONE 'UTC' ELSE value::timestamp END)+COALESCE(modifier::interval,interval '0'),'YYYY-MM-DD HH24:MI:SS')
$$;
CREATE OR REPLACE FUNCTION lume.mix(id bigint,seed bigint) RETURNS bigint LANGUAGE sql IMMUTABLE AS $$
 SELECT ('x'||substr(md5(id::text||':'||seed::text),1,8))::bit(32)::bigint
$$;
`;
const tables=db.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid").all();
for(const table of tables){
 let ddl=table.sql.replace(/^CREATE TABLE(?: IF NOT EXISTS)?\s+("?\w+"?)/i,'CREATE TABLE IF NOT EXISTS $1')
 .replace(/\bid\s+INTEGER\s+PRIMARY KEY\b/gi,'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
 .replace(/TEXT NOT NULL UNIQUE COLLATE NOCASE/gi,'extensions.citext NOT NULL UNIQUE')
 .replace(/(expires_at|next_attempt_at|used_at)(\s+)INTEGER/gi,'$1$2BIGINT');
 sql+=ddl+';\n';
 for(const column of db.prepare('PRAGMA table_info("'+table.name+'")').all())if(['expires_at','next_attempt_at','used_at'].includes(column.name)&&column.type==='INTEGER')sql+=`ALTER TABLE ${table.name} ALTER COLUMN ${column.name} TYPE BIGINT;\n`;
}
sql+=`CREATE TABLE IF NOT EXISTS realtime_events(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,kind TEXT NOT NULL,payload JSONB NOT NULL DEFAULT '{}',created_at TIMESTAMPTZ NOT NULL DEFAULT now());\n`;
sql+=`CREATE TABLE IF NOT EXISTS runtime_errors(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,path TEXT,message TEXT,code TEXT,created_at TIMESTAMPTZ DEFAULT now());\n`;
for(const table of [...tables,{name:'realtime_events'},{name:'runtime_errors'}])sql+=`ALTER TABLE lume.${table.name} ENABLE ROW LEVEL SECURITY;\nREVOKE ALL ON lume.${table.name} FROM anon,authenticated;\n`;
sql+=`REVOKE ALL ON SCHEMA lume FROM PUBLIC,anon,authenticated;
CREATE INDEX IF NOT EXISTS photo_views_recent ON photo_views(photo_id,viewed_at);
CREATE INDEX IF NOT EXISTS inspired_recent ON inspired(photo_id,created_at);
CREATE INDEX IF NOT EXISTS collection_items_recent ON collection_items(photo_id,added_at);
CREATE INDEX IF NOT EXISTS realtime_events_recent ON realtime_events(created_at);
INSERT INTO storage.buckets(id,name,public,file_size_limit,allowed_mime_types) VALUES('lume-uploads','lume-uploads',false,6291456,ARRAY['image/jpeg','image/png','image/webp']) ON CONFLICT(id) DO UPDATE SET public=false,file_size_limit=6291456,allowed_mime_types=ARRAY['image/jpeg','image/png','image/webp'];
COMMIT;\n`;
mkdirSync('supabase/migrations',{recursive:true});writeFileSync('supabase/migrations/202610230001_lume.sql',sql);db.close();
console.log('Esquema PostgreSQL gerado com RLS e sem dados privados.');
