SET search_path TO lume,extensions,public;
CREATE OR REPLACE FUNCTION lume.datetime(value text, modifier text DEFAULT NULL) RETURNS text LANGUAGE sql STABLE AS $$
 SELECT to_char((CASE WHEN value='now' THEN now() AT TIME ZONE 'UTC' ELSE value::timestamp END)+COALESCE(modifier::interval,interval '0'),'YYYY-MM-DD HH24:MI:SS')
$$;
CREATE OR REPLACE FUNCTION lume.mix(id bigint,seed bigint) RETURNS bigint LANGUAGE sql IMMUTABLE AS $$
 SELECT ('x'||substr(md5(id::text||':'||seed::text),1,8))::bit(32)::bigint
$$;
